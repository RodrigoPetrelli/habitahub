-- HabitaHub – esquema do banco (PostgreSQL, container "banco")
-- Mantenha igual a schema.sqlite.sql. Datas ficam em texto UTC no mesmo
-- formato do SQLite, para as duas versões responderem igual.

CREATE TABLE IF NOT EXISTS corretores (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome       TEXT    NOT NULL,
  email      TEXT    NOT NULL UNIQUE,
  telefone   TEXT,
  creci      TEXT    NOT NULL UNIQUE,
  ativo      INTEGER NOT NULL DEFAULT 1,
  senha_hash TEXT,    -- acesso ao sistema (scrypt); NULL = corretor sem login
  aguardando_aprovacao INTEGER NOT NULL DEFAULT 0, -- 1 = criou a conta e espera aprovação
  administrador        INTEGER NOT NULL DEFAULT 0, -- 1 = aprova contas e gerencia corretores
  criado_em  TEXT    NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS proprietarios (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome       TEXT NOT NULL,
  cpf        TEXT NOT NULL UNIQUE,
  email      TEXT NOT NULL,
  telefone   TEXT,
  criado_em  TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS clientes (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome       TEXT NOT NULL,
  cpf        TEXT NOT NULL UNIQUE,
  email      TEXT NOT NULL,
  telefone   TEXT,
  interesse  TEXT NOT NULL,
  criado_em  TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS imoveis (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo           TEXT    NOT NULL UNIQUE,
  titulo           TEXT    NOT NULL,
  tipo             TEXT    NOT NULL,
  finalidade       TEXT    NOT NULL,
  preco            DOUBLE PRECISION    NOT NULL,
  area             DOUBLE PRECISION,
  quartos          INTEGER,
  cep              TEXT,
  logradouro       TEXT,
  numero           TEXT,
  bairro           TEXT,
  cidade           TEXT    NOT NULL,
  uf               TEXT    NOT NULL,
  status           TEXT    NOT NULL DEFAULT 'Disponível',
  proprietario_id  INTEGER NOT NULL REFERENCES proprietarios(id),
  corretor_id      INTEGER NOT NULL REFERENCES corretores(id),
  criado_em        TEXT    NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS visitas (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  imovel_id    INTEGER NOT NULL REFERENCES imoveis(id),
  cliente_id   INTEGER NOT NULL REFERENCES clientes(id),
  corretor_id  INTEGER NOT NULL REFERENCES corretores(id),
  data_hora    TEXT    NOT NULL,
  status       TEXT    NOT NULL DEFAULT 'Agendada',
  feedback     TEXT,
  criado_em    TEXT    NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS propostas (
  id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  imovel_id             INTEGER NOT NULL REFERENCES imoveis(id),
  cliente_id            INTEGER NOT NULL REFERENCES clientes(id),
  valor                 DOUBLE PRECISION    NOT NULL,
  condicoes             TEXT,
  status                TEXT    NOT NULL DEFAULT 'Em análise',
  valor_contraproposta  DOUBLE PRECISION,
  criado_em             TEXT    NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS notificacoes (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  canal         TEXT NOT NULL,
  destinatario  TEXT NOT NULL,
  mensagem      TEXT NOT NULL,
  enviado_em    TEXT NOT NULL DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))
);
